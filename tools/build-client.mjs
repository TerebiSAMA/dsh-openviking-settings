/**
 * 把 `src/client.tsx` 打包成 DSH 客户端插件的 bundle。
 *
 * DSH 的客户端模块系统约定每个浏览器 bundle 是一个自注册脚本：
 *
 *   window.__ModuleLoader__.load({ id, factory: (require) => { ...; return module.exports } })
 *
 * `require()` 只能取到外壳冻结的基线模块（react、primitives 等），其余依赖必须
 * 在 bundle 内自包含。这里用 esbuild 把 TSX 打成 CommonJS，再套上这段外壳。
 */

import { build } from 'esbuild'
import { mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const entry = join(root, 'src', 'client.tsx')
const output = join(root, 'client.js')
const id = '@openviking/dsh-openviking-settings'

/** 外壳冻结的基线模块：bundle 运行时从模块表取，不打进产物。 */
const BASELINE = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/cordis',
  'zod',
  '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-dockkit',
]

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  external: BASELINE,
  legalComments: 'none',
  write: false,
  logLevel: 'info',
})

const body = result.outputFiles[0].text
const indented = body
  .split('\n')
  .map((line) => (line === '' ? '' : `    ${line}`))
  .join('\n')

const wrapped = `// Generated by tools/build-client.mjs — do not edit by hand.
// Source: src/client.tsx
window.__ModuleLoader__.load({
  id: ${JSON.stringify(id)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${indented}
    return module.exports;
  }
});
`

await mkdir(dirname(output), { recursive: true })
await writeFile(output, wrapped, 'utf8')
console.log(`built ${output} (${wrapped.length} bytes)`)
